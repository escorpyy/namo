import { sql } from "drizzle-orm";
import {
  type AnyPgColumn,
  date,
  foreignKey,
  index,
  integer,
  pgTable,
  serial,
  uniqueIndex,
  varchar,
} from "drizzle-orm/pg-core";
import { createdAt, money, updatedAt } from "./_helpers";
import { branch, company, fiscalYear, user } from "./core";
import { generalLedger, subLedger } from "./accounting";
import { location, stockDetail } from "./products";

// ============================================================
// OPENING BALANCE
// ============================================================

export const openingBalance = pgTable(
  "OpeningBalance",
  {
    id: serial().primaryKey(),
    // Denormalized from fiscalYear.companyId; filtered on nearly every report.
    companyId: integer()
      .notNull()
      .references(() => company.id, { onDelete: "restrict" }),
    branchId: integer()
      .notNull()
      .references(() => branch.id, { onDelete: "restrict" }),

    fiscalYearId: integer()
      .notNull()
      .references(() => fiscalYear.id, { onDelete: "restrict" }),

    generalLedgerId: integer()
      .notNull()
      .references(() => generalLedger.id, { onDelete: "restrict" }),

    // Narrow dimensional tag (e.g. scheme/project under one shared GL) —
    // NOT for party-wise AR/AP; every Party already has its own leaf GL.
    subLedgerId: integer().references(() => subLedger.id, {
      onDelete: "restrict",
    }),

    debit: money().notNull().default("0"),
    credit: money().notNull().default("0"),
    remarks: varchar({ length: 500 }),

    // Traces a row generated by year-end roll-forward back to the prior
    // year's closing balance it came from.
    carriedForwardFromId: integer().references(
      (): AnyPgColumn => openingBalance.id,
      { onDelete: "set null" },
    ),

    createdBy: integer().references(() => user.id, { onDelete: "set null" }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    index("OpeningBalance_companyId_idx").on(t.companyId),
    index("OpeningBalance_branchId_idx").on(t.branchId),
    // Prisma's auto-name for this composite exceeded Postgres' 63-char limit
    index("OpeningBalance_fy_branch_gl_subledger_idx").on(
      t.fiscalYearId,
      t.branchId,
      t.generalLedgerId,
      t.subLedgerId,
    ),
    index("OpeningBalance_generalLedgerId_idx").on(t.generalLedgerId),
    index("OpeningBalance_subLedgerId_idx").on(t.subLedgerId),

    // Real uniqueness. A plain composite unique would treat every NULL
    // subLedgerId as distinct, so it is split into two partial indexes.
    // (Was raw migration SQL under Prisma.)
    uniqueIndex("OpeningBalance_fy_branch_gl_nosub_key")
      .on(t.fiscalYearId, t.branchId, t.generalLedgerId)
      .where(sql`${t.subLedgerId} IS NULL`),
    uniqueIndex("OpeningBalance_fy_branch_gl_sub_key")
      .on(t.fiscalYearId, t.branchId, t.generalLedgerId, t.subLedgerId)
      .where(sql`${t.subLedgerId} IS NOT NULL`),
  ],
);

// ============================================================
// STOCK OPENING BALANCE
// ============================================================

export const stockOpeningBalance = pgTable(
  "StockOpeningBalance",
  {
    id: serial().primaryKey(),
    branchId: integer()
      .notNull()
      .references(() => branch.id, { onDelete: "restrict" }),

    fiscalYearId: integer()
      .notNull()
      .references(() => fiscalYear.id, { onDelete: "restrict" }),

    stockDetailId: integer()
      .notNull()
      .references(() => stockDetail.id, { onDelete: "restrict" }),

    locationId: integer().references(() => location.id, {
      onDelete: "set null",
    }),

    batchNo: varchar({ length: 50 }),
    expiryDate: date({ mode: "date" }),

    quantity: money().notNull(),
    rate: money().notNull(),
    // quantity * rate — stored explicitly (not generated) so a
    // transcription error is visible rather than silently masked.
    value: money().notNull(),

    // FK declared explicitly below: the auto-generated name would exceed
    // Postgres' 63-character identifier limit.
    carriedForwardFromId: integer(),

    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    foreignKey({
      name: "StockOpeningBalance_carriedForwardFromId_fkey",
      columns: [t.carriedForwardFromId],
      foreignColumns: [t.id],
    }).onDelete("set null"),
    index("StockOpeningBalance_branchId_idx").on(t.branchId),
    index("StockOpeningBalance_fiscalYearId_branchId_stockDetailId_idx").on(
      t.fiscalYearId,
      t.branchId,
      t.stockDetailId,
    ),
    index("StockOpeningBalance_stockDetailId_idx").on(t.stockDetailId),

    // locationId/batchNo are nullable, so uniqueness uses COALESCE.
    // (Was raw migration SQL under Prisma.)
    uniqueIndex("StockOpeningBalance_unique_row_key").on(
      t.fiscalYearId,
      t.branchId,
      t.stockDetailId,
      sql`COALESCE(${t.locationId}, 0)`,
      sql`COALESCE(${t.batchNo}, '')`,
    ),
  ],
);
